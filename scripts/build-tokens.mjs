// Builds CSS from the Figma export.
//
// Input:  tokens/figma-export.tsv  — raw dump made by the agent via use_figma (see directives/tokens_export.md).
//         Line kinds: V (variable), T (text style), E (one effect of an effect style). Never edit by hand.
// Output: tokens/tokens.json        — DTCG tokens (source for Style Dictionary)
//         src/tokens/tokens.css      — CSS custom properties, aliases kept as var() references
//         src/tokens/typography.css  — --typo-* font shorthands + .ds-text-* classes
//         src/tokens/meta.json       — token list with Figma names, for the Foundation docs page
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.join(root, p);

// Figma name -> CSS-safe path segments. "font/line-height/16" -> ["font","line-height","16"], "black/a3" -> ["black","a3"]
const seg = (s) =>
  s.trim().toLowerCase()
    .replace(/%/g, '')
    .replace(/&/g, 'and')
    .replace(/^-(\d)/, 'minus-$1')
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '-')
    .replace(/-+/g, '-');
const toPath = (figmaName) => figmaName.split('/').map(seg);
const toVar = (figmaName) => '--' + toPath(figmaName).join('-');
// Style names carry a DS/ prefix in Figma (DS/Heading/H1, DS/Shadow/s); CSS ids drop it.
const styleId = (styleName) => toPath(styleName.replace(/^DS\//, '')).join('-');

const WEIGHT = { Regular: 400, Medium: 500, 'Semi Bold': 600, Bold: 700 };

// ---------- parse ----------
const lines = fs.readFileSync(rel('tokens/figma-export.tsv'), 'utf8').split(/\r?\n/).filter(Boolean);
const vars = [], textStyles = [], effects = new Map();
for (const line of lines) {
  const c = line.split('\t');
  if (c[0] === 'V') vars.push({ collection: c[1], name: c[2], type: c[3], value: c[4] });
  else if (c[0] === 'T') textStyles.push({ name: c[1], family: c[2], weight: c[3], size: c[4], lineHeight: c[5], letterSpacing: c[6] });
  else if (c[0] === 'E') {
    const [, name, type, x, y, blur, spread, color] = c;
    if (!effects.has(name)) effects.set(name, []);
    effects.get(name).push({ type, x: +x, y: +y, blur: +blur, spread: +spread, color });
  } else throw new Error(`Unknown line kind: ${line}`);
}
const known = new Set(vars.map((v) => v.name));
const ref = (figmaName) => {
  if (!known.has(figmaName)) throw new Error(`Reference to unknown variable: ${figmaName}`);
  return figmaName;
};

// ---------- DTCG tokens ----------
const tokens = {};
const seen = new Map();
for (const v of vars) {
  const p = toPath(v.name);
  const key = p.join('.');
  if (seen.has(key)) throw new Error(`Name collision after sanitizing: "${v.name}" and "${seen.get(key)}" -> ${key}`);
  seen.set(key, v.name);

  const isAlias = v.value.startsWith('@');
  let $type, $value;
  if (isAlias) $value = '{' + toPath(ref(v.value.slice(1))).join('.') + '}';
  if (v.type === 'COLOR') { $type = 'color'; $value ??= v.value; }
  else if (v.type === 'FLOAT') { $type = 'dimension'; $value ??= `${+v.value}px`; }
  else if (v.name.startsWith('font/weight/')) { $type = 'fontWeight'; $value ??= WEIGHT[v.value] ?? v.value; }
  else if (v.name === 'font/sans') { $type = 'fontFamily'; $value ??= v.value; }
  else { $type = 'string'; $value ??= v.value; }

  let o = tokens;
  for (const k of p.slice(0, -1)) o = o[k] ??= {};
  o[p.at(-1)] = { $type, $value, $extensions: { figma: { name: v.name, collection: v.collection } } };
}
fs.mkdirSync(rel('tokens'), { recursive: true });
fs.writeFileSync(rel('tokens/tokens.json'), JSON.stringify(tokens, null, 2) + '\n');

// ---------- Style Dictionary: tokens.css ----------
const sd = new StyleDictionary({
  source: [rel('tokens/tokens.json')],
  log: { verbosity: 'default' },
  hooks: {
    transforms: { 'name/ds': { type: 'name', transform: (t) => t.path.join('-') } },
  },
  platforms: {
    css: {
      transforms: ['name/ds'],
      buildPath: rel('src/tokens') + path.sep,
      files: [{
        destination: 'tokens.css',
        format: 'css/variables',
        options: { outputReferences: true, selector: ':root', fileHeader: () => ['Generated by scripts/build-tokens.mjs from tokens/figma-export.tsv — do not edit.'] },
      }],
    },
  },
});
await sd.buildAllPlatforms();

// ---------- typography + shadows ----------
const header = '/* Generated by scripts/build-tokens.mjs from tokens/figma-export.tsv — do not edit. */\n';
// Line height: a variable name, or a raw value when the style's line height is not bound (120% -> 1.2, 24px, auto -> normal).
const lineHeightCss = (v) => /%$/.test(v) ? String(parseFloat(v) / 100) : /px$/.test(v) ? v : v === 'auto' ? 'normal' : `var(${toVar(ref(v))})`;
const typoVars = [], typoClasses = [], meta = { typography: [], shadows: [] };
for (const s of textStyles) {
  const id = styleId(s.name);
  const fam = `var(${toVar(ref(s.family))}), system-ui, sans-serif`;
  typoVars.push(`  --typo-${id}: var(${toVar(ref(s.weight))}) var(${toVar(ref(s.size))})/${lineHeightCss(s.lineHeight)} ${fam};`);
  const ls = s.letterSpacing.endsWith('%') ? `${parseFloat(s.letterSpacing) / 100}em` : s.letterSpacing;
  typoClasses.push(`.ds-text-${id} {\n  font: var(--typo-${id});\n  letter-spacing: ${parseFloat(ls) === 0 ? '0' : ls};\n}`);
  meta.typography.push({ figma: s.name, cssVar: `--typo-${id}`, className: `ds-text-${id}` });
}
const shadowVars = [];
for (const [name, list] of effects) {
  const id = /^DS\/(Shadow|Effect)\//.test(name) ? styleId(name) : 'shadow-' + styleId(name);
  const parts = list.map((e) => {
    const color = e.color.startsWith('@') ? `var(${toVar(ref(e.color.slice(1)))})` : e.color;
    return `${e.type === 'INNER_SHADOW' ? 'inset ' : ''}${e.x}px ${e.y}px ${e.blur}px ${e.spread}px ${color}`;
  });
  shadowVars.push(`  --${id}: ${parts.join(', ')};`);
  meta.shadows.push({ figma: name, cssVar: `--${id}` });
}
fs.writeFileSync(rel('src/tokens/typography.css'),
  header + ':root {\n' + typoVars.join('\n') + '\n' + shadowVars.join('\n') + '\n}\n\n' + typoClasses.join('\n\n') + '\n');

meta.variables = vars.map((v) => ({
  figma: v.name, collection: v.collection, type: v.type, cssVar: toVar(v.name),
  value: v.value.startsWith('@') ? null : v.value, alias: v.value.startsWith('@') ? toVar(v.value.slice(1)) : null,
}));
fs.writeFileSync(rel('src/tokens/meta.json'), JSON.stringify(meta, null, 2) + '\n');

console.log(`tokens: ${vars.length} variables, ${textStyles.length} text styles, ${effects.size} effect styles`);
